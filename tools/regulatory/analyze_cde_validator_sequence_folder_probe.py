from __future__ import annotations

"""Compare an isolated sequence-folder probe with the frozen 0000 control.

This tool deliberately limits the comparison to facts generated by the same
transaction harness or to control invariants frozen after three repeated 0000
runs. It does not classify any individual validation rule and therefore never
increments the calibration-informative counter.
"""

import argparse
import json
from pathlib import Path
from typing import Any

WARNING_FRAGMENT = "序列文件夹不是数字"


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def warning_dialogs(transaction: dict[str, Any]) -> list[dict[str, Any]]:
    dialogs: list[dict[str, Any]] = []
    for event in transaction.get("action_trace", []):
        if event.get("action") != "confirm_native_dialog":
            continue
        texts = [str(item) for item in event.get("texts", [])]
        dialogs.append(
            {
                "at": event.get("at"),
                "button": event.get("button"),
                "texts": texts,
                "sequence_folder_warning": any(WARNING_FRAGMENT in item for item in texts),
            }
        )
    return dialogs


def render_markdown(payload: dict[str, Any]) -> str:
    probe = payload["probe"]
    comparison = payload["comparison"]
    totals = probe["native_report_semantics"]["severity_totals"]
    lines = [
        "# CDE 验证器序列目录名隔离试验：0000 → 0001",
        "",
        f"- Case：`{probe['case_id']}`",
        f"- 事务：`{probe['run_id']}`",
        f"- 事务状态：**{probe['status']}**",
        f"- 官方黑盒观察可采信：**{probe['admissible']}**",
        f"- 目录：`{probe['input_directory']}`",
        f"- 仍出现“序列文件夹不是数字”：**{probe['sequence_folder_warning_present']}**",
        f"- 原生报告规则条目：{probe['native_report_semantics']['rule_count']}",
        f"- 提示 / 警告 / 错误：{totals.get('提示信息', 0)} / {totals.get('警告', 0)} / {totals.get('错误', 0)}",
        "",
        "## 与三次 0000 控制结果比较",
        "",
        f"- 严重度总数相同：**{comparison['same_severity_totals_as_control']}**",
        f"- 可见规则条目相同：**{comparison['same_rule_count_as_control']}**",
        f"- 路径警告在 0001 中持续：**{comparison['warning_persists_with_0001']}**",
        f"- 结论：**{payload['conclusion']}**",
        "",
        "## 解释边界",
        "",
        "该试验只改变所选空目录的末级名称。若 0001 仍出现同一提示，则不能把提示简单解释为 0000 的保留序列号；还需检查官方程序对“选择目录层级”的预期、父目录结构和空目录前置条件。该结果仍不是 PDF 规则校准。",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--transaction", type=Path, required=True)
    parser.add_argument("--native-summary", type=Path, required=True)
    parser.add_argument("--control-stability", type=Path, required=True)
    parser.add_argument("--json", type=Path, required=True)
    parser.add_argument("--markdown", type=Path)
    args = parser.parse_args()

    transaction = read_json(args.transaction)
    native = read_json(args.native_summary)
    control = read_json(args.control_stability)
    dialogs = warning_dialogs(transaction)
    warning_present = any(item["sequence_folder_warning"] for item in dialogs)

    control_observations = control.get("observations", [])
    if not control_observations:
        raise ValueError("control stability file has no observations")
    control_semantics = control_observations[0]["semantic_summary"]
    control_totals = control_semantics["severity_totals"]
    control_rule_count = int(control_semantics["visible_rule_count"])

    probe_totals = native.get("summary", {}).get("totals", {})
    probe_rule_count = int(native.get("rule_count") or 0)
    input_directory = str(transaction.get("input", {}).get("directory") or "")
    if not input_directory.replace("/", "\\").endswith("\\0001"):
        raise ValueError(f"probe did not select the required 0001 directory: {input_directory}")
    if transaction.get("case_id") != "cn-v11-probe-001-invalid-empty-root-0001":
        raise ValueError(f"unexpected case id: {transaction.get('case_id')}")

    same_totals = probe_totals == control_totals
    same_rule_count = probe_rule_count == control_rule_count
    conclusion = (
        "WARNING_PERSISTS_WITH_0001"
        if warning_present
        else "WARNING_ABSENT_WITH_0001"
    )

    payload = {
        "schema_version": "0.1.0",
        "experiment": "isolated_sequence_folder_name_0000_to_0001",
        "single_changed_variable": {
            "name": "selected sequence folder name",
            "control": "0000",
            "probe": "0001",
        },
        "probe": {
            "run_id": transaction.get("run_id"),
            "case_id": transaction.get("case_id"),
            "status": transaction.get("status"),
            "admissible": bool(transaction.get("admissible_official_black_box_observation")),
            "input_directory": input_directory,
            "input_unchanged": transaction.get("input", {}).get("unchanged"),
            "validation_invoked": transaction.get("validation_invoked"),
            "native_report_present": transaction.get("native_result", {}).get("native_report_present"),
            "sequence_folder_warning_present": warning_present,
            "confirmed_native_dialogs": dialogs,
            "final_native_terminal": (
                transaction.get("native_result", {}).get("terminal_alert", {}).get("texts", [])
            ),
            "native_report_semantics": {
                "rule_count": probe_rule_count,
                "severity_totals": probe_totals,
                "normalized_visible_text_sha256": native.get("normalization", {}).get(
                    "normalized_visible_text_sha256"
                ),
                "semantic_contract_sha256": native.get("normalization", {}).get(
                    "semantic_contract_sha256"
                ),
                "reported_sequence": native.get("metadata", {}).get("序列号"),
            },
        },
        "control": {
            "case_id": control.get("case", {}).get("case_id"),
            "observation_count": control.get("stability_assessment", {}).get("observation_count"),
            "sequence_folder_warning_present_in_all_runs": control.get(
                "stability_assessment", {}
            ).get("same_pre_validation_warning"),
            "rule_count": control_rule_count,
            "severity_totals": control_totals,
        },
        "comparison": {
            "warning_persists_with_0001": warning_present,
            "same_rule_count_as_control": same_rule_count,
            "same_severity_totals_as_control": same_totals,
            "semantic_hash_directly_comparable": False,
            "semantic_hash_comparison_note": "The frozen control hashes were produced before parser schema 0.2.0; reprocess raw control artifacts with the same parser before asserting exact semantic-hash equality.",
        },
        "conclusion": conclusion,
        "counters": {
            "official_black_box_observation_increment_if_admissible": 1,
            "calibration_informative_observation_increment": 0,
        },
        "boundary": "Path-selection behavior experiment only; not evidence of a valid eCTD sequence, submission acceptance, detector calibration or stock-environment parity.",
    }

    if not payload["probe"]["admissible"]:
        raise ValueError("probe transaction is not admissible")
    if not payload["probe"]["validation_invoked"]:
        raise ValueError("validation was not invoked")
    if not payload["probe"]["native_report_present"]:
        raise ValueError("native report was not produced")
    if payload["probe"]["input_unchanged"] is not True:
        raise ValueError("input integrity gate failed")

    write_json(args.json, payload)
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(render_markdown(payload), encoding="utf-8")
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
